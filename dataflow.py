"""Data-Flow Analysis Framework for CVM.

Provides:
- DataFlowAnalysis: Generic worklist-based solver (forward & backward)
- LivenessAnalysis: Backward, union meet (live variables)
- ReachingDefinitions: Forward, union meet (definitions reaching each point)
- AvailableExpressions: Forward, intersection meet (available expressions)
- DataFlowResults: Container for IN, OUT, GEN, and KILL sets
- pretty_print: Formatted debug visualization
"""
from collections import deque
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional, Set, Tuple, Union

from ir import (
    Assign, BinOp, Call, Goto, IfNz, IfZ, Label, Print, Return,
    LoadIndexed, StoreIndexed, NewArray, VLoad, VStore, VAdd, VSub, VMul, VDiv
)
from optimizer import BasicBlock

Operand = Union[int, str]
DefTuple = Tuple[str, str, int]  # (variable, block_label, instruction_index)
ExprTuple = Tuple[str, Operand, Operand]  # (op, operand1, operand2)


def _get_read_vars(ins) -> List[str]:
    """Extract variable names read/used by an instruction."""
    if isinstance(ins, Assign):
        return [ins.src] if isinstance(ins.src, str) else []
    elif isinstance(ins, BinOp):
        return [v for v in (ins.a, ins.b) if isinstance(v, str)]
    elif isinstance(ins, (IfZ, IfNz)):
        return [ins.cond] if isinstance(ins.cond, str) else []
    elif isinstance(ins, Print):
        return [ins.arg] if isinstance(ins.arg, str) else []
    elif isinstance(ins, Return):
        return [ins.arg] if ins.arg is not None and isinstance(ins.arg, str) else []
    elif isinstance(ins, Call):
        return [a for a in ins.args if isinstance(a, str)]
    elif isinstance(ins, LoadIndexed):
        res = [ins.array] if isinstance(ins.array, str) else []
        if isinstance(ins.index, str):
            res.append(ins.index)
        return res
    elif isinstance(ins, StoreIndexed):
        res = [ins.array] if isinstance(ins.array, str) else []
        if isinstance(ins.index, str):
            res.append(ins.index)
        if isinstance(ins.src, str):
            res.append(ins.src)
        return res
    elif isinstance(ins, NewArray):
        return [ins.size] if isinstance(ins.size, str) else []
    elif isinstance(ins, VLoad):
        res = [ins.array] if isinstance(ins.array, str) else []
        if isinstance(ins.base_index, str):
            res.append(ins.base_index)
        return res
    elif isinstance(ins, VStore):
        res = [ins.array] if isinstance(ins.array, str) else []
        if isinstance(ins.base_index, str):
            res.append(ins.base_index)
        if isinstance(ins.src, str):
            res.append(ins.src)
        return res
    elif isinstance(ins, (VAdd, VSub, VMul, VDiv)):
        return [v for v in (ins.a, ins.b) if isinstance(v, str)]
    return []


def _get_def_var(ins) -> Optional[str]:
    """Extract variable name defined/assigned by an instruction, if any."""
    if isinstance(ins, (Assign, BinOp)):
        return ins.dst
    if isinstance(ins, Call):
        return ins.dst
    if isinstance(ins, (LoadIndexed, NewArray, VLoad, VAdd, VSub, VMul, VDiv)):
        return ins.dst
    return None


@dataclass
class DataFlowResults:
    """Holds dataflow analysis facts for all blocks."""
    in_sets: Dict[str, Set[Any]]
    out_sets: Dict[str, Set[Any]]
    gen_sets: Dict[str, Set[Any]] = field(default_factory=dict)
    kill_sets: Dict[str, Set[Any]] = field(default_factory=dict)


class DataFlowAnalysis:
    """Generic forward and backward worklist data-flow analysis engine."""
    direction: str = "forward"  # "forward" or "backward"

    def gen(self, block: BasicBlock) -> Set[Any]:
        """Compute set of facts generated by block."""
        raise NotImplementedError

    def kill(self, block: BasicBlock) -> Set[Any]:
        """Compute set of facts killed by block."""
        raise NotImplementedError

    def meet(self, sets: List[Set[Any]]) -> Set[Any]:
        """Combine incoming/outgoing dataflow sets (union or intersection)."""
        raise NotImplementedError

    def initial_val(self, block: BasicBlock) -> Set[Any]:
        """Initial value for internal blocks before iteration (empty set or top/universal)."""
        return set()

    def boundary_val(self) -> Set[Any]:
        """Value at program entry (forward) or exit (backward) boundary."""
        return set()

    def transfer(self, block: BasicBlock, in_fact: Set[Any]) -> Set[Any]:
        """Transfer function: gen(b) union (in_fact - kill(b))."""
        return self.gen_sets[block.label] | (in_fact - self.kill_sets[block.label])

    def setup(self, cfg: Dict[str, BasicBlock]):
        """Optional hook called before worklist execution to gather global program facts."""
        pass

    def run(self, cfg: Dict[str, BasicBlock]) -> DataFlowResults:
        """Execute the worklist algorithm until fixed point is reached."""
        if not cfg:
            return DataFlowResults(in_sets={}, out_sets={}, gen_sets={}, kill_sets={})

        self.setup(cfg)
        self.gen_sets = {lbl: self.gen(b) for lbl, b in cfg.items()}
        self.kill_sets = {lbl: self.kill(b) for lbl, b in cfg.items()}

        is_forward = (self.direction == "forward")
        entry_label = next(iter(cfg.keys()))

        in_sets: Dict[str, Set[Any]] = {}
        out_sets: Dict[str, Set[Any]] = {}

        if is_forward:
            for lbl, b in cfg.items():
                if lbl == entry_label or not b.preds:
                    in_sets[lbl] = set(self.boundary_val())
                    out_sets[lbl] = self.transfer(b, in_sets[lbl])
                else:
                    in_sets[lbl] = set(self.initial_val(b))
                    out_sets[lbl] = set(self.initial_val(b))
            worklist = deque(cfg.keys())
        else:
            for lbl, b in cfg.items():
                if not b.succs:
                    out_sets[lbl] = set(self.boundary_val())
                    in_sets[lbl] = self.transfer(b, out_sets[lbl])
                else:
                    out_sets[lbl] = set(self.initial_val(b))
                    in_sets[lbl] = set(self.initial_val(b))
            worklist = deque(reversed(list(cfg.keys())))

        in_worklist = set(worklist)

        while worklist:
            lbl = worklist.popleft()
            in_worklist.discard(lbl)
            b = cfg[lbl]

            if is_forward:
                if lbl == entry_label and not b.preds:
                    current_in = set(self.boundary_val())
                else:
                    pred_outs = [out_sets[p] for p in b.preds if p in out_sets]
                    if pred_outs:
                        current_in = self.meet(pred_outs)
                        if lbl == entry_label:
                            current_in = self.meet([set(self.boundary_val())] + pred_outs)
                    else:
                        current_in = set(self.boundary_val())

                in_sets[lbl] = current_in
                new_out = self.transfer(b, current_in)
                if new_out != out_sets[lbl]:
                    out_sets[lbl] = new_out
                    for s in b.succs:
                        if s in cfg and s not in in_worklist:
                            worklist.append(s)
                            in_worklist.add(s)

            else:  # backward
                if not b.succs:
                    current_out = set(self.boundary_val())
                else:
                    succ_ins = [in_sets[s] for s in b.succs if s in in_sets]
                    if succ_ins:
                        current_out = self.meet(succ_ins)
                    else:
                        current_out = set(self.boundary_val())

                out_sets[lbl] = current_out
                new_in = self.transfer(b, current_out)
                if new_in != in_sets[lbl]:
                    in_sets[lbl] = new_in
                    for p in b.preds:
                        if p in cfg and p not in in_worklist:
                            worklist.append(p)
                            in_worklist.add(p)

        return DataFlowResults(
            in_sets=in_sets,
            out_sets=out_sets,
            gen_sets=self.gen_sets,
            kill_sets=self.kill_sets,
        )


class LivenessAnalysis(DataFlowAnalysis):
    """Backward dataflow analysis computing live variables."""
    direction = "backward"

    def meet(self, sets: List[Set[str]]) -> Set[str]:
        """Union confluence operator combining live variable sets across successors."""
        if not sets:
            return set()
        return set().union(*sets)

    def gen(self, block: BasicBlock) -> Set[str]:
        """Variables used before being defined in block."""
        gen_set = set()
        def_set = set()
        for ins in block.instrs:
            for v in _get_read_vars(ins):
                if v not in def_set:
                    gen_set.add(v)
            dst = _get_def_var(ins)
            if dst:
                def_set.add(dst)
        return gen_set

    def kill(self, block: BasicBlock) -> Set[str]:
        """Variables defined in block."""
        kill_set = set()
        for ins in block.instrs:
            dst = _get_def_var(ins)
            if dst:
                kill_set.add(dst)
        return kill_set


class ReachingDefinitions(DataFlowAnalysis):
    """Forward dataflow analysis computing definitions reaching each program point."""
    direction = "forward"

    def setup(self, cfg: Dict[str, BasicBlock]):
        """Index all definitions across the CFG."""
        self.all_defs: Set[DefTuple] = set()
        self.var_defs: Dict[str, Set[DefTuple]] = {}
        for lbl, b in cfg.items():
            for idx, ins in enumerate(b.instrs):
                dst = _get_def_var(ins)
                if dst:
                    d: DefTuple = (dst, lbl, idx)
                    self.all_defs.add(d)
                    self.var_defs.setdefault(dst, set()).add(d)

    def meet(self, sets: List[Set[DefTuple]]) -> Set[DefTuple]:
        """Union confluence operator combining reaching definition sets across predecessors."""
        if not sets:
            return set()
        return set().union(*sets)

    def gen(self, block: BasicBlock) -> Set[DefTuple]:
        """Downward-exposed definitions in block."""
        gen_map: Dict[str, DefTuple] = {}
        for idx, ins in enumerate(block.instrs):
            dst = _get_def_var(ins)
            if dst:
                gen_map[dst] = (dst, block.label, idx)
        return set(gen_map.values())

    def kill(self, block: BasicBlock) -> Set[DefTuple]:
        """All definitions of variables defined in this block across the CFG."""
        kill_set = set()
        for ins in block.instrs:
            dst = _get_def_var(ins)
            if dst:
                kill_set.update(self.var_defs.get(dst, set()))
        return kill_set


class AvailableExpressions(DataFlowAnalysis):
    """Forward dataflow analysis computing available binary expressions."""
    direction = "forward"

    def setup(self, cfg: Dict[str, BasicBlock]):
        """Collect universe of all binary expressions in CFG."""
        self.all_exprs: Set[ExprTuple] = set()
        for b in cfg.values():
            for ins in b.instrs:
                if isinstance(ins, BinOp):
                    self.all_exprs.add((ins.op, ins.a, ins.b))

    def meet(self, sets: List[Set[ExprTuple]]) -> Set[ExprTuple]:
        """Intersection confluence operator combining available expression sets across predecessors."""
        if not sets:
            return set()
        res = set(sets[0])
        for s in sets[1:]:
            res &= s
        return res

    def initial_val(self, block: BasicBlock) -> Set[ExprTuple]:
        """Non-entry blocks initialized to top (universal set of all expressions)."""
        return set(self.all_exprs)

    def boundary_val(self) -> Set[ExprTuple]:
        """At program entry, no expressions are available."""
        return set()

    def gen(self, block: BasicBlock) -> Set[ExprTuple]:
        """Expressions computed in block whose operands are not subsequently redefined."""
        avail: Set[ExprTuple] = set()
        for ins in block.instrs:
            if isinstance(ins, BinOp):
                avail.add((ins.op, ins.a, ins.b))
            dst = _get_def_var(ins)
            if dst:
                avail = {e for e in avail if e[1] != dst and e[2] != dst}
        return avail

    def kill(self, block: BasicBlock) -> Set[ExprTuple]:
        """Any expression in universe whose operands are defined anywhere in block."""
        defs = set()
        for ins in block.instrs:
            dst = _get_def_var(ins)
            if dst:
                defs.add(dst)
        return {e for e in self.all_exprs if e[1] in defs or e[2] in defs}


def pretty_print(results: DataFlowResults, cfg: Dict[str, BasicBlock]) -> str:
    """Format dataflow results into readable text for debug visualization."""
    lines = []
    for lbl, b in cfg.items():
        lines.append(f"Block: {lbl}")
        lines.append(f"  Preds: {b.preds}, Succs: {b.succs}")
        in_f = sorted(str(x) for x in results.in_sets.get(lbl, set()))
        out_f = sorted(str(x) for x in results.out_sets.get(lbl, set()))
        gen_f = sorted(str(x) for x in results.gen_sets.get(lbl, set()))
        kill_f = sorted(str(x) for x in results.kill_sets.get(lbl, set()))
        lines.append(f"  IN:   {in_f}")
        lines.append(f"  GEN:  {gen_f}")
        lines.append(f"  KILL: {kill_f}")
        lines.append(f"  OUT:  {out_f}")
        lines.append("  Instructions:")
        for idx, ins in enumerate(b.instrs):
            lines.append(f"    [{idx}] {ins}")
        lines.append("")
    return "\n".join(lines)
